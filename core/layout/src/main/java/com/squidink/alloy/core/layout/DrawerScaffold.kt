/**
 * Simple scaffold with modal navigation drawer and top app bar.
 * 
 * Features:
 * - Modal navigation drawer accessible via hamburger menu (always visible)
 * - Top app bar with hamburger + title
 * - Single content area - features manage their own detail panes
 * 
 * @param navigationContent Content to display in the navigation drawer
 * @param title The title to display in the top app bar
 * @param content The main content area
 * @param modifier Modifier to apply to the root container
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun DrawerScaffold(
    navigationContent: @Composable () -> Unit,
    title: String,
    content: @Composable () -> Unit,
    modifier: Modifier = Modifier
) {
    val drawerState = rememberDrawerState(initialValue = DrawerValue.Closed)
    val scope = rememberCoroutineScope()
    
    ModalNavigationDrawer(
        drawerState = drawerState,
        drawerContent = {
            ModalDrawerSheet {
                navigationContent()
            }
        }
    ) {
        Scaffold(
            topBar = {
                TopAppBar(
                    title = { Text(title) },
                    navigationIcon = {
                        IconButton(
                            onClick = { scope.launch { drawerState.open() } }
                        ) {
                            Icon(
                                imageVector = Icons.Default.Menu,
                                contentDescription = "Open navigation"
                            )
                        }
                    }
                )
            }
        ) { paddingValues ->
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(paddingValues)
            ) {
                content()
            }
        }
    }
}
